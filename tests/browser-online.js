globalThis.onlineErrors=[];
page.on('pageerror',e=>onlineErrors.push(String(e)));
const response=await page.goto('https://17timg-bit.github.io/stargram/',{waitUntil:'domcontentloaded'});
assert.equal(response.status(),200);
await expect(page).toHaveTitle('星轨留声机 · STARGRAM');
await page.getByRole('button',{name:'开始演奏',exact:true}).click();
await page.waitForFunction(()=>Stargram.status().encounters>=6,{timeout:15000});
assert.equal(await page.evaluate(()=>Stargram.status().audioState),'running');
await page.getByRole('button',{name:'暂停演奏',exact:true}).click();
await page.waitForFunction(()=>Stargram.status().activeVoices===0,{timeout:3000});
await page.getByRole('button',{name:'选择浮光轨道',exact:true}).click();
const before=await page.evaluate(()=>Stargram.snapshot());
await page.getByRole('button',{name:'第2格，空白',exact:true}).click();
assert.equal(await page.evaluate(()=>Stargram.snapshot().tracks[2].notes[1]),2);
await page.reload({waitUntil:'domcontentloaded'});
assert.equal(await page.evaluate(()=>Stargram.snapshot().tracks[2].notes[1]),2);
await page.getByRole('button',{name:/晨雾中的信号/}).click();
const state=await page.evaluate(()=>Stargram.snapshot());
expect(state).toEqual(before);
assert.equal(onlineErrors.length,0);
return {url:page.url(),httpStatus:response.status(),title:await page.title(),checks:['public URL opens','audio clock and encounters run after click','pause clears scheduled voices','note edit persists across real reload','preset restored'],errors:onlineErrors,screenshot:await page.screenshot({fullPage:false})};
